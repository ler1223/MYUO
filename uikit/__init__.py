"""Движок интерфейса поверх pygame: тема из файла, текст, раскладка, нарисованные рамки, виджеты, слои.

Как устроено (снизу вверх):
  text    — шрифты из файлов темы, стили текста (шрифт, размер, цвет, тень, обводка), выравнивание
            по высоте заглавных (текст в рамке стоит ровно посередине), обрезка «…», перенос строк
  layout  — чистые функции над прямоугольниками: отступы, ряды и колонки с долями, сетка,
            привязка к краю/центру, группа по центру; экраны собираются из них, а не из чисел
  skin    — рамки 9-slice по телу: все состояния виджета выравниваются по одной внутренней области
            (картинки разного размера не «прыгают»); полосы из конца и тела, собранные на месте
  gui     — Gui (наследник pygame_ui.UI): тема, стили, слои отрисовки (поверх — позже),
            перекрытие мыши (верхний слой забирает наведение и клики)
  widgets — рамка, панель, кнопка, вкладка, строка, ячейка с картинкой, полоса, раздел, ромбики

Тема — assets/ui/theme.json (размеры тел рамок замеряет tools/measure_ui_art.py).
"""
